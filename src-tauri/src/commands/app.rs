use serde::Serialize;
use specta::Type;
use tauri::{AppHandle, Manager, State};

use crate::error::{AppError, AppResult};
use crate::paths;
use crate::state::AppState;

/// Version and system directories of the running app.
#[derive(Debug, Serialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct AppInfo {
    pub version: String,
    pub config_dir: String,
    pub data_dir: String,
    pub log_dir: String,
}

#[tauri::command]
#[specta::specta]
pub fn app_info(app: AppHandle) -> AppResult<AppInfo> {
    let data_dir = app
        .path()
        .app_data_dir()
        .map_err(|error| AppError::PathUnavailable(format!("data: {error}")))?;
    let info = AppInfo {
        version: app.package_info().version.to_string(),
        config_dir: paths::config_dir(&app)?.display().to_string(),
        data_dir: data_dir.display().to_string(),
        log_dir: paths::log_dir(&app)?.display().to_string(),
    };
    tracing::debug!(?info, "app_info");
    Ok(info)
}

/// Suggested parent folder for new worlds: the one chosen in the settings,
/// else `Documents/Atlasaga` (or `Documents/BuilderZ` if it exists, ADR 0016).
#[tauri::command]
#[specta::specta]
pub async fn default_worlds_dir(app: AppHandle, state: State<'_, AppState>) -> AppResult<String> {
    if let Some(dir) = state.settings.lock().await.default_worlds_dir.clone() {
        return Ok(dir);
    }
    Ok(paths::default_worlds_dir(&app)?.display().to_string())
}

/// File name of the third-party notices among the app's resources
/// (`bundle.resources` in tauri.conf.json, generated by `pnpm notices`).
const THIRD_PARTY_NOTICES: &str = "THIRD-PARTY-NOTICES.txt";

/// Text of the third-party notices shipped with the app (Settings › About).
#[tauri::command]
#[specta::specta]
pub async fn third_party_notices(app: AppHandle) -> AppResult<String> {
    let path = app
        .path()
        .resource_dir()
        .map_err(|error| AppError::PathUnavailable(format!("resources: {error}")))?
        .join(THIRD_PARTY_NOTICES);
    Ok(tokio::fs::read_to_string(path).await?)
}
